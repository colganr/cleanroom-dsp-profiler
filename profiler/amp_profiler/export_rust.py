"""
Pure-Rust Weight Module Code Generator.

Emits ready-to-compile Rust tensor source files (`amp_weights.rs`, `pedal_weights.rs`)
directly consumable by `dsp-core-rust` (`WienerHammersteinAmp` & `OverdriveEngine`).
"""

from __future__ import annotations

from pathlib import Path
import numpy as np


def _fmt_f32_row(arr: np.ndarray) -> str:
    return ", ".join(f"{float(v):.8e}_f32" for v in arr)


def export_amp_rust_weights(
    out_path: str | Path,
    base_pre_ir: np.ndarray,
    base_post_ir: np.ndarray,
    gain_brackets: list[float],
    weights_by_bracket: np.ndarray,
    prefix: str = "CAPTURED_AMP",
) -> Path:
    """Writes a drop-in Pure-Rust weight file for `WienerHammersteinAmp`."""
    p = Path(out_path)
    p.parent.mkdir(parents=True, exist_ok=True)
    w = np.asarray(weights_by_bracket, dtype=np.float32)
    if w.ndim == 1:
        w = w[None, :]
    n_brk, n_ch = w.shape

    lines = [
        "// Auto-generated by cleanroom-dsp-profiler — DO NOT EDIT MANUALLY.",
        f"pub const {prefix}_GAIN_BRACKETS: [f32; {len(gain_brackets)}] = [{', '.join(f'{g:.4f}_f32' for g in gain_brackets)}];",
        f"pub const {prefix}_BASE_PRE_IR: [f32; {len(base_pre_ir)}] = [{_fmt_f32_row(base_pre_ir)}];",
        f"pub const {prefix}_BASE_POST_IR: [f32; {len(base_post_ir)}] = [{_fmt_f32_row(base_post_ir)}];",
        f"pub const {prefix}_WEIGHTS: [[f32; {n_ch}]; {n_brk}] = [",
    ]
    for b in range(n_brk):
        lines.append(f"    [{_fmt_f32_row(w[b])}],")
    lines.append("];\n")

    p.write_text("\n".join(lines), encoding="utf-8")
    return p


def export_pedal_rust_weights(
    out_path: str | Path,
    pre_ir_21: np.ndarray,
    post_ir_21: np.ndarray,
    level_gain_21: np.ndarray,
    gain_brackets: list[float],
    weights_by_bracket: np.ndarray,
    prefix: str = "CAPTURED_PEDAL",
) -> Path:
    """Writes a drop-in Pure-Rust weight file for `OverdriveEngine`."""
    p = Path(out_path)
    p.parent.mkdir(parents=True, exist_ok=True)
    w = np.asarray(weights_by_bracket, dtype=np.float32)
    if w.ndim == 1:
        w = w[None, :]
    n_brk, n_ch = w.shape
    fir_len = pre_ir_21.shape[1]

    lines = [
        "// Auto-generated by cleanroom-dsp-profiler — DO NOT EDIT MANUALLY.",
        f"pub const {prefix}_GAIN_BRACKETS: [f32; {len(gain_brackets)}] = [{', '.join(f'{g:.4f}_f32' for g in gain_brackets)}];",
        f"pub const {prefix}_LEVEL_GAIN_21: [f32; {len(level_gain_21)}] = [{_fmt_f32_row(level_gain_21)}];",
        f"pub const {prefix}_PRE_IR_21: [[f32; {fir_len}]; {len(pre_ir_21)}] = [",
    ]
    for row in pre_ir_21:
        lines.append(f"    [{_fmt_f32_row(row)}],")
    lines.append("];")
    lines.append(f"pub const {prefix}_POST_IR_21: [[f32; {fir_len}]; {len(post_ir_21)}] = [")
    for row in post_ir_21:
        lines.append(f"    [{_fmt_f32_row(row)}],")
    lines.append("];")
    lines.append(f"pub const {prefix}_WEIGHTS: [[f32; {n_ch}]; {n_brk}] = [")
    for b in range(n_brk):
        lines.append(f"    [{_fmt_f32_row(w[b])}],")
    lines.append("];\n")

    p.write_text("\n".join(lines), encoding="utf-8")
    return p
