"""
Scalable 2D/3D Speaker Cabinet IR Grid Capturer & `i16 + f32` Quantizer.

Captures `1024`-tap `48 kHz` impulse responses across spatial `(Position x Distance)` or
`(Axis x Distance x Angle)` knots and quantizes them into little-endian `i16` + per-IR
`f32` peak scales (`-96.3 dB` noise floor, 50% smaller than raw float32).
"""

from __future__ import annotations

from pathlib import Path
import numpy as np
from .backends.base import TargetBackend


def quantize_cab_grid(irs: np.ndarray) -> tuple[bytes, np.ndarray]:
    """
    Quantizes an array of IRs `(N_irs, ir_len)` into little-endian `i16` bytes + `f32` scales.
    """
    arr = np.asarray(irs, dtype=np.float32)
    if arr.ndim != 2:
        raise ValueError(f"Expected 2D array (N_irs, ir_len), got shape {arr.shape}")

    n_irs, ir_len = arr.shape
    scales = np.zeros(n_irs, dtype=np.float32)
    q_all = np.zeros((n_irs, ir_len), dtype="<i2")

    for i in range(n_irs):
        pk = float(np.max(np.abs(arr[i])))
        if pk < 1e-9:
            scales[i] = 0.0
            continue
        scales[i] = pk
        scaled = np.clip(np.round((arr[i] / pk) * 32767.0), -32767.0, 32767.0)
        q_all[i] = scaled.astype("<i2")

    return q_all.tobytes(), scales


def dequantize_cab_grid(grid_bytes: bytes, scales: np.ndarray, ir_len: int = 1024) -> np.ndarray:
    """Inverse of `quantize_cab_grid` for verification & null-testing."""
    n_irs = len(scales)
    q = np.frombuffer(grid_bytes, dtype="<i2").reshape(n_irs, ir_len).astype(np.float32)
    return q * (scales[:, None] / np.float32(32767.0))


def capture_cab_grid(
    backend: TargetBackend,
    pid_cab: int | None,
    pid_mic: int | None,
    pid_pos: int | None,
    pid_dist: int | None,
    pid_angle: int | None = None,
    cab_values: list[float] | None = None,
    mic_values: list[float] | None = None,
    pos_knots: list[float] | None = None,
    dist_knots: list[float] | None = None,
    angle_knots: list[float] | None = None,
    onset: int = 0,
    ir_len: int = 1024,
    imp_amp: float = 0.5,
) -> tuple[bytes, np.ndarray, dict]:
    """Captures all spatial cabinet IR knots sequentially on `backend`."""
    cabs = cab_values or [0.0]
    mics = mic_values or [0.0]
    poss = pos_knots or [0.0, 0.5, 1.0]
    dists = dist_knots or [0.0, 1.0]
    angs = angle_knots or [0.0]

    imp = np.zeros(256 + onset + ir_len + 128, dtype=np.float32)
    imp[128] = imp_amp

    irs = []
    for c_val in cabs:
        if pid_cab is not None:
            backend.set_param(pid_cab, float(c_val))
        for m_val in mics:
            if pid_mic is not None:
                backend.set_param(pid_mic, float(m_val))
            for p_val in poss:
                if pid_pos is not None:
                    backend.set_param(pid_pos, float(p_val))
                for d_val in dists:
                    if pid_dist is not None:
                        backend.set_param(pid_dist, float(d_val))
                    for a_val in angs:
                        if pid_angle is not None:
                            backend.set_param(pid_angle, float(a_val))
                        backend.settle(full=False)
                        y = backend.render_mono(imp)
                        start = 128 + onset
                        ir = (y[start : start + ir_len].astype(np.float64) / imp_amp).astype(np.float32)
                        irs.append(ir)

    ir_mat = np.stack(irs, axis=0)
    grid_bytes, scales = quantize_cab_grid(ir_mat)
    meta = {
        "num_cabs": len(cabs),
        "num_mics": len(mics),
        "n_pos": len(poss),
        "n_dist": len(dists),
        "n_angle": len(angs),
        "ir_len": ir_len,
        "total_irs": len(irs),
        "sample_rate": backend.sr,
    }
    return grid_bytes, scales, meta


def save_cab_grid_artifacts(
    out_dir: str | Path,
    prefix: str,
    grid_bytes: bytes,
    scales: np.ndarray,
    meta: dict,
) -> tuple[Path, Path]:
    """Writes `<prefix>_cab_grid.bin` and `<prefix>_cab_scales.rs`."""
    d = Path(out_dir)
    d.mkdir(parents=True, exist_ok=True)
    bin_path = d / f"{prefix}_cab_grid.bin"
    rs_path = d / f"{prefix}_cab_scales.rs"

    bin_path.write_bytes(grid_bytes)

    lines = [
        f"// Auto-generated by cleanroom-dsp-profiler ({meta['total_irs']} quantized i16 IRs @ {meta['sample_rate']} Hz)",
        f"pub const CAB_NUM_CABS: usize = {meta['num_cabs']};",
        f"pub const CAB_NUM_MICS: usize = {meta['num_mics']};",
        f"pub const CAB_N_POS: usize = {meta['n_pos']};",
        f"pub const CAB_N_DIST: usize = {meta['n_dist']};",
        f"pub const CAB_N_ANGLE: usize = {meta['n_angle']};",
        f"pub const CAB_GRID_SCALES: [f32; {len(scales)}] = [",
    ]
    for i in range(0, len(scales), 8):
        chunk = ", ".join(f"{float(v):.8e}_f32" for v in scales[i : i + 8])
        lines.append(f"    {chunk},")
    lines.append("];\n")
    rs_path.write_text("\n".join(lines), encoding="utf-8")
    return bin_path, rs_path
